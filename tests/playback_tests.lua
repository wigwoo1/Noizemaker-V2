local playback = require("core.playback")
local audio = require("core.game_audio")
local report = require("core.report")
local format = require("core.format")
local r = report.load(TEST_GAME_ROOT, 1)
local original = r.files[1].entries[1]
local bank = audio.command_bank(TEST_GAME_ROOT, "r11")
assert(audio.command_for_code(0x21,"r11")=="CHU" and audio.command_for_code(0x41,"r11")=="CHU",
    "Recorded R11 flagged Chu events use the ordinary Chu voice")
assert(audio.command_for_code(0x41,"r12")=="0x41" and audio.command_for_code(0x31,"r11")=="0x31",
    "Voice aliases do not generalize to unverified flags or sections")
assert(audio.command_for_code(9,"r11")=="HOLDCHU" and audio.command_for_code(9,"r12")=="CHU")
assert(bank.samples.HOLDCHU.name=="se/r11/bank02_r11/04shoottame.adx"
    and bank.samples.HOLDCHU.info.duration>0.89 and bank.samples.HOLDCHU.info.duration<0.91,
    "Held Chu uses the recorded 0.9-second take, not the 1.61-second alternate")
local extended={steps={9},hits={},timing=16,start_delay=0}
local held_plan=playback.plan(extended,120,nil,nil,"r11")
local held_wav=playback.render(held_plan,bank)
assert(held_plan.events[1].command=="HOLDCHU"
    and held_wav:sub(45,44+#bank.samples.HOLDCHU.pcm)==bank.samples.HOLDCHU.pcm,
    "Phrase render places the complete original held-Chu PCM at the command onset")
for _,code in ipairs({0x21,0x41}) do
    local flagged={steps={code},hits={},timing=16,start_delay=0}
    local flagged_plan=playback.plan(flagged,120,nil,nil,"r11")
    local flagged_wav=playback.render(flagged_plan,bank)
    assert(flagged.steps[1]==code and flagged_plan.events[1].code==code and flagged_plan.events[1].command=="CHU")
    assert(flagged_wav:sub(45,44+#bank.samples.CHU.pcm)==bank.samples.CHU.pcm,
        "Flagged Chu renders normal Chu audio while preserving its original chart byte")
end
local section_banks = {
    r11 = "bank00_ulala1", r12 = "bank00u1", r21 = "bank00u1  normal",
    r22 = "bank00_ulala1", r23 = "bank00_ulala1", r31 = "bank00_u1",
    r41 = "bank00_ulala1", r42 = "bank00_ulala1", r43 = "bank00u1  normal",
    r44 = "bank00", r51 = "bank00_ulala1", r52 = "bank00u1",
    r61 = "bank00_ulala_r61", r62 = "bank00",
}
for stem, expected_bank in pairs(section_banks) do
    local section_bank = stem == "r11" and bank or audio.command_bank(TEST_GAME_ROOT, stem)
    assert(section_bank.bank_name == expected_bank, stem .. " uses its indexed English command bank")
    assert(not section_bank.shared_source, stem .. " must not silently borrow R11 command audio")
    for _, command in ipairs({"UP", "RIGHT", "LEFT", "DOWN", "CHU", "HEY"}) do
        assert(section_bank.samples[command], stem .. " must decode all six English command samples")
        assert(section_bank.samples[command].name:find("/" .. expected_bank .. "/", 1, true),
            stem .. " sample must come from its section-specific bank")
    end
end
local plan = playback.plan(original)
assert(plan.bpm == 120 and plan.duration == 4, "opening phrase is eight beats at 120 BPM")
assert(#plan.events == 3 and plan.events[1].seconds == 0 and plan.events[2].seconds == 1 and plan.events[3].seconds == 2,
    "opening calls are two beats apart")
local wav, info = playback.render(plan, bank)
assert(info.count == 176400 and #wav == 44 + 176400 * 2, "exact phrase length")
local pcm = wav:sub(45)
assert(pcm:sub(1, #bank.samples.UP.pcm) == bank.samples.UP.pcm, "first note must contain the real English UP sample")
assert(pcm:sub(#bank.samples.UP.pcm + 1, 44100) == string.rep("\0", 44100 - #bank.samples.UP.pcm), "silence between spoken commands")
assert(plan.events[2].sample_offset == 44100 and plan.events[3].sample_offset == 88200, "sample-accurate command placement")

local slice = playback.plan(original, 120, 24, 48)
assert(#slice.events == 1 and slice.events[1].index == 2 and slice.events[1].seconds == 0 and slice.duration == 1,
    "selected loop range includes its starting note and excludes the next note")
local faster = playback.plan(original, 240)
assert(faster.duration == 2 and faster.events[2].seconds == 0.5, "tempo changes rescale all notes together")
local delayed = {steps = {3, 0, 1}, hits = {24, 24}, timing = 16, start_delay = 12}
local delayed_plan = playback.plan(delayed, 120)
assert(#delayed_plan.events == 2 and delayed_plan.events[1].seconds == 0.5 and delayed_plan.events[2].seconds == 2.5,
    "start delay and silent rest retain their chart time")
assert(not pcall(playback.plan, original, 120, 48, 24), "reversed ranges are rejected")
assert(not pcall(playback.render, playback.plan({steps = {255}, hits = {}, timing = 16}, 120), bank), "unknown command must not silently disappear")
assert(not pcall(audio.parse_resource, "\0\0\0\0"), "truncated archive must be rejected")

-- Independent regression evidence from the actual CPU run, not values
-- generated by the preview's timing conversion.
local evidence_file = assert(io.open(TEST_FIXTURE_ROOT .. "/report1-timing.json", "rb"))
local evidence = require("core.json").decode(evidence_file:read("*a")); evidence_file:close()
local captured
for _, entry in ipairs(r.files[1].entries) do if entry.name == evidence.entry then captured = entry end end
assert(captured and evidence.clock_samples >= 40, "live game evidence must identify an imported English phrase")
local actual = playback.plan(captured)
assert(actual.bpm == evidence.bpm and math.abs(actual.duration-evidence.expected_duration_seconds)<0.000001,
    "preview tempo and phrase length must match the live engine")
assert(#actual.events == #evidence.expected_note_seconds, "same number of live and preview commands")
for i, event in ipairs(actual.events) do
    assert(event.code == evidence.codes[i] and math.abs(event.seconds-evidence.expected_note_seconds[i])<0.000001,
        "preview note onset must match live game timing")
end
assert(require("ui.timeline").summary_text(original):find("8 beats",1,true), "timeline beat labels match playback")
local fallback_bpm, fallback_source = playback.tempo({})
assert(fallback_bpm == 120 and fallback_source == "fallback", "missing tempo is explicitly a fallback")
assert(playback.plan(original).tempo_source == "chart" and playback.plan(original,90).tempo_source == "manual",
    "automatic and manual preview tempos stay distinguishable")
print("PASS: preview matches captured live Report 1 " .. evidence.question .. " -> " .. evidence.entry .. " note times and phrase length")

